/** UI 板 mm-presets/mm-key 浏览器验收:预设卡只填 Key → 写本机密钥文件;UI 掩码末4位;配置无明文。 */
const { chromium } = require("playwright-core");
const { readFileSync } = require("node:fs");
const BASE = process.env.PANEL_BASE || "http://127.0.0.1:7791";
const ROOT = process.env.FIXTURE_ROOT || "/tmp/gh-ui-repo";
(async () => {
  const browser = await chromium.launch({ executablePath: "/usr/bin/google-chrome", headless: true, args: ["--no-sandbox", "--disable-dev-shm-usage", "--no-proxy-server"] });
  const page = await browser.newPage({ viewport: { width: 1500, height: 1000 } });
  const errs = [];
  page.on("pageerror", (e) => errs.push(String(e).slice(0, 160)));
  const results = [];
  const check = (n, ok, d = "") => { results.push({ n, ok }); console.log((ok ? "PASS" : "FAIL") + " " + n + (d ? " — " + d : "")); };
  await page.goto(BASE + "/", { waitUntil: "domcontentloaded" });
  await page.waitForTimeout(1200);
  await page.evaluate(() => { switchView("sys"); setSection("model"); });
  await page.waitForTimeout(500);
  await page.click("#prov-add-open");
  await page.waitForTimeout(250);
  const card = page.locator("#provPresets .preset-card").filter({ hasText: "DeepSeek" }).first();
  check("添加弹窗内预设卡在场(DeepSeek)", await card.count() === 1 && await card.isVisible());
  await card.click();
  await page.waitForTimeout(400);
  check("预设对话框打开", await page.locator(".uid-box.pp-box").isVisible());
  const sub = (await page.locator(".pp-sub").textContent()) || "";
  check("对话框只要求填 Key", /只需填写 API Key/.test(sub), sub.trim());
  check("Key 输入为 password", (await page.locator('.pp-key').getAttribute("type")) === "password");
  const disabled = page.locator(".pp-mode.disabled");
  check("无 Token 套餐 Tab 灰置", (await disabled.count()) === 1 && /无 Token 套餐/.test(await disabled.textContent()), (await disabled.textContent() || "").trim());
  const adv = page.locator(".pp-adv");
  check("baseUrl/模型预填在可展开高级区", (await adv.count()) === 1 && !(await adv.getAttribute("open")));
  await page.fill(".pp-key", "sk-test-abcd1234");
  await page.click(".uid-ok");
  await page.waitForTimeout(1200);
  check("对话框已关闭", (await page.locator(".uid-box.pp-box").count()) === 0);
  const provText = (await page.locator("#prov-list").textContent()) || "";
  check("Provider 卡显示密钥引用名", provText.includes("DEEPSEEK_API_KEY"), provText.slice(-260));
  check("Provider 卡显示掩码末4位", provText.includes("••••1234"), provText.slice(-260));
  const secrets = readFileSync(ROOT + "/.genie/secrets.json", "utf8");
  const cfg = readFileSync(ROOT + "/genie.config.json", "utf8");
  check("密钥写入本机 secrets", secrets.includes("DEEPSEEK_API_KEY") && secrets.includes("sk-test-abcd1234"));
  check("配置文件无明文 key", !cfg.includes("sk-test-abcd1234") && !/sk-test/.test(cfg));
  check("零 pageerror", errs.length === 0, errs.join(" | "));
  await page.screenshot({ path: "/tmp/modelpage-key.png", fullPage: true });
  await browser.close();
  const failed = results.filter((r) => !r.ok);
  console.log(failed.length === 0 ? "ALL PASS " + results.length : "FAILED " + failed.length + "/" + results.length);
  process.exit(failed.length === 0 ? 0 : 1);
})();
